# 1. SPECIFICATION ORACLE & MATHEMATICAL CONTRACTS
# ==============================================================================
class TestV2SpecOracleContracts(unittest.TestCase):
    """Verify mathematical properties and data integrity of the V2 dataset."""

    def test_v2_total_message_count_math(self):
        """Verify total messages equals sum of Hamid and Amina messages."""
        m = oracle_v2.CHAT_METRICS_V2
        self.assertEqual(m['total_messages'], 18589)
        self.assertEqual(m['hamid_messages'], 9301)
        self.assertEqual(m['amina_messages'], 9288)
        self.assertEqual(m['hamid_messages'] + m['amina_messages'], m['total_messages'])

    def test_v2_partner_balance_percentages(self):
        """Verify 50.03% vs 49.97% partner balance with 13-message delta."""
        m = oracle_v2.CHAT_METRICS_V2
        hamid_pct = round((m['hamid_messages'] / m['total_messages']) * 100, 2)
        amina_pct = round((m['amina_messages'] / m['total_messages']) * 100, 2)
        self.assertEqual(hamid_pct, 50.03)
        self.assertEqual(amina_pct, 49.97)
        self.assertEqual(m['hamid_messages'] - m['amina_messages'], 13)

    def test_v2_monthly_progression_math(self):
        """Verify monthly message totals and daily averages."""
        monthly = oracle_v2.CHAT_METRICS_V2['monthly_progression']
        self.assertEqual(monthly['july']['total'], 2610)
        self.assertEqual(monthly['august']['total'], 10489)
        self.assertEqual(monthly['september']['total'], 5490)
        total = monthly['july']['total'] + monthly['august']['total'] + monthly['september']['total']
        self.assertEqual(total, 18589)

        # Verify daily velocities
        self.assertAlmostEqual(monthly['july']['daily_avg'], 113.5, places=1)
        self.assertAlmostEqual(monthly['august']['daily_avg'], 338.4, places=1)
        self.assertAlmostEqual(monthly['september']['daily_avg'], 366.0, places=1)

    def test_v2_peak_day_contract(self):
        """Verify peak day date and volume (Mon 17 Aug with 857 msgs)."""
        peak = oracle_v2.CHAT_METRICS_V2['peak_day']
        self.assertEqual(peak['total'], 857)
        self.assertEqual(peak['hamid'], 457)
        self.assertEqual(peak['amina'], 400)
        self.assertEqual(peak['hamid'] + peak['amina'], 857)
        self.assertIn("17 August 2026", peak['day_str'])

    def test_v2_midnight_intimacy_math(self):
        """Verify midnight window (8,730 msgs) and peak hour (00:00-01:00 with 3,762 msgs)."""
        mid = oracle_v2.CHAT_METRICS_V2['midnight_chats']
        self.assertEqual(mid['total'], 8730)
        self.assertEqual(mid['peak_hour_count'], 3762)
        self.assertAlmostEqual(mid['percentage'], 46.96, places=2)
        self.assertEqual(mid['hamid_count'] + mid['amina_count'], 8730)

    def test_v2_reaction_leaderboard_math(self):
        """Verify total reactions (3,368), Amina Queen (2,604 / 77.3%), top emojis (👍 1,569, ❤️ 667)."""
        rxn = oracle_v2.CHAT_METRICS_V2['reactions']
        self.assertEqual(rxn['total'], 3368)
        self.assertEqual(rxn['amina_count'], 2604)
        self.assertEqual(rxn['hamid_count'], 764)
        self.assertEqual(rxn['amina_count'] + rxn['hamid_count'], 3368)
        self.assertAlmostEqual(rxn['amina_pct'], 77.32, places=1)
        self.assertEqual(rxn['top_emojis']['👍'], 1569)
        self.assertEqual(rxn['top_emojis']['❤️'], 667)

    def test_v2_sweet_words_counts(self):
        """Verify sweet words frequencies (yaad 96, love 48, jaan 40, pyaar 39)."""
        sw = oracle_v2.CHAT_METRICS_V2['sweet_words']
        self.assertEqual(sw['yaad'], 96)
        self.assertEqual(sw['love'], 48)
        self.assertEqual(sw['jaan'], 40)
        self.assertEqual(sw['pyaar'], 39)

    def test_v2_longest_break_contract(self):
        """Verify longest break duration 47.94h and flight message."""
        lb = oracle_v2.CHAT_METRICS_V2['longest_break']
        self.assertEqual(lb['duration_hours'], 47.94)
        self.assertEqual(lb['broken_by'], 'Amina Chamadiya')
        self.assertIn('flight', lb['message_text'].lower())

    def test_v2_love_quiz_answer_distribution(self):
        """Verify Love Quiz 2.0 non-predictable answer distribution (B, D, A, C, B)."""
        q = oracle_v2.LOVE_QUIZ_2_CONTRACT
        self.assertEqual(q['total_questions'], 5)
