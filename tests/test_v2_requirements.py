# 6. ZERO PROHIBITED VERSION WORDS IN USER COPY
# ==============================================================================
class TestV2ZeroProhibitedWords(BaseV2TestCase):
    """Verify absence of technical version labels, build hashes, and debug labels."""

    def test_v2_no_prohibited_version_words_in_user_copy(self):
        """Assert no 'v1.0', 'beta', 'debug mode', '(NEW ANALYTICS)' in visible user text."""
        self.require_v2_file()
        # Strip script and style blocks before checking user-visible copy
        body_copy = re.sub(r'<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>', '', self.v2_content, flags=re.IGNORECASE)
        body_copy = re.sub(r'<style\b[^<]*(?:(?!<\/style>)<[^<]*)*<\/style>', '', body_copy, flags=re.IGNORECASE)
        body_copy = re.sub(r'<!--.*?-->', '', body_copy, flags=re.DOTALL)

        violations = oracle_v2.ZeroVersionValidatorV2.scan(body_copy)
        self.assertEqual(
            len(violations),
            0,
            f"Found prohibited version or debug words in user-visible copy: {violations}"
        )


